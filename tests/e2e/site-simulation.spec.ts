import { test, expect } from "@playwright/test";
import { atlasFrame } from "./risk-fixtures";

test("site scenario stays isolated, preserves unknowns, supports modal keyboard, mobile and offline", async ({ page, context }) => {
  const errors: string[] = [], writes: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("request", r => { if (r.url().includes("/api/") && r.method() !== "GET") writes.push(r.url()); });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.route("**/api/sites/*/screening", r => r.fulfill({ status: 503, json: { error: "No screening" } }));
  await page.route("**/api/risk/atlas?**", r => r.fulfill({ json: atlasFrame(0) }));
  await page.goto("/?view=atlas");
  await expect(page.locator(".three-map-canvas")).toHaveAttribute("data-geography", "ready", { timeout: 30000 });
  const riskBefore = await page.getByTestId("atlas-risk").innerText();
  const launch = page.getByRole("button", { name: "Open 3D simulation" });
  await launch.click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toBeVisible({ timeout: 30000 });
  await expect(dialog.getByRole("button", { name: "Close simulation" })).toBeFocused();
  await expect(dialog.locator("canvas")).toHaveCount(1);
  await expect(dialog.locator("fieldset input, fieldset select")).toHaveCount(34);
  await expect(dialog.getByRole("button", { name: "Play animation" })).toBeVisible();
  const heat = dialog.getByLabel("Heat index (°F)", { exact: true });
  const baseline = await heat.inputValue();
  await heat.fill("120"); await heat.press("Tab");
  await expect(heat).toHaveValue("120");
  await dialog.getByRole("button", { name: "Reset inputs" }).click();
  await expect(heat).toHaveValue(baseline);
  await heat.fill(""); await heat.press("Tab"); await expect(heat).toHaveValue("");
  const humidity = dialog.getByLabel("Relative humidity (%)", { exact: true });
  await humidity.fill("110"); await humidity.press("Tab");
  await expect(dialog.getByRole("alert")).toContainText("outside the accepted range");
  await dialog.getByRole("button", { name: "Reset inputs" }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  const scrollArea = dialog.locator(".simulation-layout");
  await scrollArea.evaluate(el => { el.scrollTop = el.scrollHeight; });
  await expect(dialog.getByRole("button", { name: "Close simulation" })).toBeInViewport();
  await scrollArea.evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: "test-results/site-simulation-mobile.png" });
  await page.keyboard.press("Escape"); await expect(dialog).toHaveCount(0);
  await expect(launch).toBeFocused();
  await expect(page.getByTestId("atlas-risk")).toHaveText(riskBefore);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(async () => {
    const registration = await navigator.serviceWorker.ready;
    if (!navigator.serviceWorker.controller) await new Promise<void>(resolve => navigator.serviceWorker.addEventListener("controllerchange", () => resolve(), { once: true }));
    return registration.active?.state;
  });
  await context.setOffline(true);
  await page.reload();
  await launch.click(); await expect(dialog.locator("canvas")).toHaveCount(1);
  await dialog.getByRole("button", { name: "Try extreme heat" }).click();
  await expect(heat).toHaveValue("120");
  await dialog.getByRole("button", { name: "Try a storm" }).click();
  await expect(dialog.getByLabel("Wind gust (mph)", { exact: true })).toHaveValue("50");
  await page.screenshot({ path: "test-results/site-simulation-desktop.png" });
  await dialog.getByRole("button", { name: "Close simulation" }).click();
  await context.setOffline(false);
  expect(writes).toEqual([]); expect(errors).toEqual([]);
});

test("environment studio renders distinct weather, soil and event views without inventing detected locations", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error" && /THREE|shader|WebGLProgram/.test(m.text())) errors.push(m.text()); });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.route("**/api/sites/*/screening", r => r.fulfill({ status: 503, json: { error: "No screening" } }));
  await page.route("**/api/risk/atlas?**", r => r.fulfill({ json: atlasFrame(0) }));
  await page.goto("/?view=atlas");
  const launcher = page.getByRole("button", { name: "Open 3D simulation" });
  await expect(launcher).toHaveCSS("border-radius", "12px");
  await launcher.click();
  const dialog = page.getByRole("dialog"), canvas = dialog.locator("canvas");
  await expect(canvas).toHaveAttribute("data-context", "ready", { timeout: 30000 });
  await expect(canvas).toHaveAttribute("data-demonstration", "none");
  const initialGeometry = await canvas.getAttribute("data-geometries");
  const moisture = await canvas.getAttribute("data-surface-moisture");
  await dialog.getByRole("button", { name: "Try extreme heat", exact: true }).click();
  await expect(canvas).toHaveAttribute("data-lens", "heat");
  await expect(canvas).toHaveAttribute("data-heat", "1");
  await expect(canvas).toHaveAttribute("data-surface-moisture", moisture!);
  await dialog.locator(".simulation-stage").screenshot({ path: "test-results/simulation-heat.png" });
  await dialog.getByRole("button", { name: "Try a storm", exact: true }).click();
  await expect(canvas).toHaveAttribute("data-precipitation", "rain-replay");
  await expect(canvas).toHaveAttribute("data-demonstration", "lightning");
  await expect(dialog.locator(".simulation-demo-label")).toContainText("arbitrary position");
  await dialog.locator(".simulation-stage").screenshot({ path: "test-results/simulation-storm.png" });
  await dialog.getByRole("button", { name: "Snowfall", exact: true }).click();
  await expect(canvas).toHaveAttribute("data-precipitation", "snow");
  await dialog.locator(".simulation-stage").screenshot({ path: "test-results/simulation-snow.png" });
  await dialog.getByRole("button", { name: "Wet ground", exact: true }).click();
  await expect(canvas).toHaveAttribute("data-lens", "soil");
  await expect(canvas).toHaveAttribute("data-camera-view", "detail");
  await expect(dialog.getByText("Surface VWC", { exact: true })).toBeVisible();
  await dialog.locator(".simulation-stage").screenshot({ path: "test-results/simulation-ground.png" });
  await dialog.getByRole("button", { name: "Water", exact: true }).click();
  await expect(dialog.locator(".simulation-lens-note")).toContainText("do not locate flooding");
  await dialog.locator(".simulation-stage").screenshot({ path: "test-results/simulation-water.png" });
  await dialog.getByRole("button", { name: "Fire demonstration", exact: true }).click();
  await expect(canvas).toHaveAttribute("data-demonstration", "fire");
  await expect(dialog.getByLabel("Hypothetical event evidence")).toContainText("Location / perimeter unknown");
  await dialog.locator(".simulation-stage").screenshot({ path: "test-results/simulation-fire.png" });
  await dialog.getByText("Scene & demonstration controls", { exact: true }).click();
  await dialog.getByLabel("Demonstration effect", { exact: true }).selectOption("none");
  await expect(canvas).toHaveAttribute("data-demonstration", "none");
  await dialog.getByLabel("Illustrative facility template").selectOption("solar");
  await expect(canvas).toHaveAttribute("data-template", "solar");
  await dialog.locator(".simulation-stage").screenshot({ path: "test-results/simulation-solar.png" });
  await dialog.getByLabel("Illustrative facility template").selectOption("substation");
  await expect(canvas).toHaveAttribute("data-template", "substation");
  await dialog.getByRole("button", { name: "Overhead", exact: true }).click();
  await expect(canvas).toHaveAttribute("data-camera-view", "overhead");
  await dialog.getByRole("button", { name: "Clear skies", exact: true }).click();
  await expect(canvas).toHaveAttribute("data-precipitation", "none");
  // GPU buffers upload lazily the first time a template/effect becomes visible.
  const warmedGeometry = await canvas.getAttribute("data-geometries");
  for (const label of ["Try extreme heat", "Try a storm", "Snowfall", "Wet ground", "Fire demonstration", "Clear skies"]) {
    await dialog.getByRole("button", { name: label, exact: true }).click();
  }
  await expect(canvas).toHaveAttribute("data-geometries", warmedGeometry!);
  const pausedFrames = await canvas.getAttribute("data-frames");
  await page.waitForTimeout(350);
  await expect(canvas).toHaveAttribute("data-frames", pausedFrames!);
  await dialog.getByRole("button", { name: "Play animation", exact: true }).click();
  await expect.poll(async () => Number(await canvas.getAttribute("data-frames"))).toBeGreaterThan(Number(pausedFrames) + 2);
  await dialog.getByRole("button", { name: "Pause animation", exact: true }).click();
  await dialog.getByRole("button", { name: "Close simulation" }).click();
  await launcher.click();
  await expect(dialog.locator("canvas")).toHaveAttribute("data-geometries", initialGeometry!, { timeout: 30000 });
  await dialog.getByRole("button", { name: "Close simulation" }).click();
  expect(errors).toEqual([]);
});

test("studio preserves accessible scenario controls when graphics are unavailable", async ({ page }) => {
  await page.addInitScript(() => {
    const getContext = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function (this: HTMLCanvasElement, type: string, ...args: unknown[]) {
      if (type === "webgl" || type === "webgl2" || type === "experimental-webgl") return null;
      return Reflect.apply(getContext, this, [type, ...args]);
    } as typeof getContext;
  });
  await page.goto("/?view=atlas");
  await page.getByRole("button", { name: "Open 3D simulation" }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByRole("status")).toContainText("3D graphics unavailable", { timeout: 30000 });
  await expect(dialog.locator("fieldset input, fieldset select")).toHaveCount(34);
  await dialog.getByRole("button", { name: "Try extreme heat", exact: true }).click();
  await expect(dialog.getByLabel("Heat index (°F)", { exact: true })).toHaveValue("120");
  await expect(dialog.getByLabel("Current operational restrictions")).toBeAttached();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "Open 3D simulation" })).toBeFocused();
});
